# apps.py
# Конфигурация приложения files
# Определяет настройки и метаданные приложения для работы с файлами

from django.apps import AppConfig


class FilesConfig(AppConfig):
    """
    Класс конфигурации приложения files.
    Определяет базовые настройки приложения для управления файлами.
    """

    # Имя приложения (используется Django для идентификации)
    default_auto_field = "django.db.models.BigAutoField"
    
    # Название приложения (отображается в админ-панели)
    name = "files"
    
    # Человекочитаемое название приложения
    verbose_name = "Управление файлами"


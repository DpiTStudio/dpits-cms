#!/usr/bin/env python
"""
Утилита командной строки для административных задач.

Этот файл является точкой входа для выполнения команд из командной строки.
Позволяет запускать сервер разработки, применять миграции, создавать суперпользователя и т.д.
"""
import os  # Импорт модуля для работы с переменными окружения
import sys  # Импорт модуля для работы с аргументами командной строки


def main():
    """
    Главная функция для выполнения административных задач.
    
    Устанавливает модуль настроек и выполняет команды из командной строки.
    Обрабатывает ошибки импорта с информативными сообщениями.
    
    Raises:
        ImportError: Если система не установлена или не доступна в PYTHONPATH
    """
    # Устанавливаем модуль настроек по умолчанию
    # Это указывает системе, где искать файл settings.py
    os.environ.setdefault('DJANGO_SETTINGS_MODULE', 'mysite.settings')
    
    try:
        # Импортируем функцию для выполнения команд Django из командной строки
        from django.core.management import execute_from_command_line
    except ImportError as exc:
        # Если система не установлена, выводим понятное сообщение об ошибке
        raise ImportError(
            "Не удалось импортировать системные компоненты. Убедитесь, что всё установлено и "
            "доступно в переменной окружения PYTHONPATH. Возможно, вы забыли "
            "активировать виртуальное окружение?"
        ) from exc
    
    # Выполняем команду Django из аргументов командной строки
    # sys.argv содержит список аргументов, переданных скрипту
    execute_from_command_line(sys.argv)


# Если скрипт запущен напрямую (а не импортирован как модуль)
if __name__ == '__main__':
    # Вызываем главную функцию
    main()

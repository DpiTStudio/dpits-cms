# Назначение: Контекстный процессор для Django.
# Добавляет объект корзины во все шаблоны автоматически.

from .cart import Cart


def cart(request):
    """
    Контекстный процессор.
    Возвращает словарь, который будет добавлен в контекст каждого шаблона.
    """
    # В каждом шаблоне будет доступна переменная {{ cart }}
    return {'cart': Cart(request)}